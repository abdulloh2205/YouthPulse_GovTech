let currentLang = localStorage.getItem('yp_lang') || 'uz';
let currentTheme = localStorage.getItem('yp_theme') || 'light';

function t(key) {
  return (i18n[currentLang] || i18n.uz)[key] || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val) el.textContent = val;
  });
  document.documentElement.lang = currentLang === 'ru' ? 'ru' : 'uz';
}

function renderHeroTitle() {
  const el = document.getElementById('hero-title-el');
  if (!el) return;
  if (currentLang === 'ru') {
    el.innerHTML = '<span class="text-accent">Интеллектуальная</span> система управления<br>занятостью молодёжи';
  } else {
    el.innerHTML = 'Yoshlar bandligini <span class="text-accent">intellektual</span><br>boshqarish tizimi';
  }
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('yp_lang', lang);
  applyI18n();
  renderHeroTitle();
  document.querySelectorAll('.lang-pill').forEach(function(btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  document.querySelectorAll('.lang-btn').forEach(function(btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

window.setLang = setLang;

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  const icon = document.getElementById('theme-icon');
  if (icon) icon.textContent = theme === 'dark' ? '☀️' : '🌙';
}

function toggleTheme() {
  currentTheme = currentTheme === 'light' ? 'dark' : 'light';
  localStorage.setItem('yp_theme', currentTheme);
  applyTheme(currentTheme);
}

window.toggleTheme = toggleTheme;

function toggleMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const btn = document.getElementById('mobile-menu-btn');
  if (!menu) return;
  const isOpen = menu.classList.toggle('open');
  menu.setAttribute('aria-hidden', String(!isOpen));
  if (btn) btn.setAttribute('aria-expanded', String(isOpen));
}

window.toggleMobileMenu = toggleMobileMenu;

function handleHeaderScroll() {
  const header = document.getElementById('site-header');
  if (!header) return;
  if (window.scrollY > 10) {
    header.classList.add('scrolled');
  } else {
    header.classList.remove('scrolled');
  }
}

document.addEventListener('DOMContentLoaded', function() {
  applyTheme(currentTheme);
  applyI18n();
  renderHeroTitle();
  setLang(currentLang);

  window.addEventListener('scroll', handleHeaderScroll, { passive: true });

  document.querySelectorAll('a[href^="#"]').forEach(function(anchor) {
    anchor.addEventListener('click', function(e) {
      const target = document.querySelector(anchor.getAttribute('href'));
      if (target) {
        e.preventDefault();
        const headerH = document.getElementById('site-header')?.offsetHeight || 68;
        const top = target.getBoundingClientRect().top + window.scrollY - headerH - 20;
        window.scrollTo({ top: top, behavior: 'smooth' });
        const menu = document.getElementById('mobile-menu');
        if (menu && menu.classList.contains('open')) {
          menu.classList.remove('open');
          menu.setAttribute('aria-hidden', 'true');
        }
      }
    });
  });

  const observer = new IntersectionObserver(function(entries) {
    entries.forEach(function(entry) {
      if (entry.isIntersecting) {
        entry.target.style.opacity = '1';
        entry.target.style.transform = 'translateY(0)';
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -40px 0px' });

  document.querySelectorAll('.feature-card, .stat-block, .step-item').forEach(function(el) {
    el.style.opacity = '0';
    el.style.transform = 'translateY(24px)';
    el.style.transition = 'opacity 0.5s ease, transform 0.5s ease';
    observer.observe(el);
  });
});
